#!/usr/bin/env python3
"""
trend_trope_remixer.py — Viral Trope Remix & What-If Spin-Off Story Engine
==========================================================================
ระบบสร้างตอนพิเศษและจักรวาลคู่ขนาน (Alternate Universe / Spin-off):
1. Trope Remix Engine: ผสมผสานตัวละครดังเข้ากับเซ็ตติ้งเทรนด์ฮิต (เช่น มาเฟีย, ไอดอล, โลกอนาคต)
2. Holiday & Festival Specials: สังเคราะห์ตอนพิเศษตามเทศกาล (วาเลนไทน์, ฮาโลวีน, ปีใหม่)
3. One-Click Spin-off Kit: บันทึกลงใน SecondBrain/05_Active_Projects/Spin_Offs/
"""

from __future__ import annotations

import os
import sys
import json
from typing import Dict, Any, List, Optional

ROOT = os.path.dirname(os.path.abspath(__file__))
SECOND_BRAIN = os.environ.get("ANSRE_SB", os.path.join(ROOT, "SecondBrain"))
SPIN_OFF_DIR = os.path.join(SECOND_BRAIN, "05_Active_Projects", "Spin_Offs")
os.makedirs(SPIN_OFF_DIR, exist_ok=True)

TROPE_TEMPLATES = {
    "modern_au": {
        "title_prefix": "[What-If: ยุคปัจจุบัน]",
        "theme": "เมื่อตัวละครยุคอดีตทะลุมิติมาใช้ชีวิตในกรุงเทพฯ ศตวรรษที่ 21",
        "keywords": ["คาเฟ่", "รถไฟฟ้า", "สมาร์ตโฟน", "สตรีมเมอร์"]
    },
    "role_reversal": {
        "title_prefix": "[What-If: สลับบทบาท]",
        "theme": "เมื่อนางร้ายกลายเป็นประธานบริษัทผู้ทรงอิทธิพล และท่านประธานกลายเป็นเด็กฝึกงาน!",
        "keywords": ["อำนาจ", "สลับขั้ว", "แกล้งคืน", "คลั่งรัก"]
    },
    "holiday_special": {
        "title_prefix": "[ตอนพิเศษเทศกาล]",
        "theme": "ค่ำคืนเทศกาลแสงไฟและความทรงจำสุดโรแมนติกที่ไม่มีวันลืม",
        "keywords": ["ดอกไม้ไฟ", "ของขวัญ", "คำสารภาพรัก", "คืนหิมะตก"]
    }
}


def generate_spin_off_chapter(
    original_title: str,
    trope_key: str = "modern_au"
) -> Dict[str, Any]:
    """สร้างตอนพิเศษ Spin-Off ตามแนวเทรนด์"""
    trope = TROPE_TEMPLATES.get(trope_key, TROPE_TEMPLATES["modern_au"])
    clean_title = original_title.replace("_", " ")

    spin_off_title = f"{trope['title_prefix']} {clean_title}"
    
    if "คุณแม่ลูกแฝด" in clean_title:
        prose = (
            f"# {spin_off_title}\n\n"
            f"**ผู้แต่ง:** เงาพันจันทร์ | **คอนเซ็ปต์:** {trope['theme']}\n\n"
            f"---\n\n"
            f"เสียง 'ติ๊งต่อง! ต้อนรับเข้าสู่ร้านสะดวกซื้อค่ะ' ดังก้องไปทั่วห้างสรรพสินค้าใจกลางสยามสแควร์\n\n"
            f"หลินม่านในชุดสูทผู้บริหารสีขาวสะอาดยืนกอดอกมองจอมอนิเตอร์กล้องวงจรปิดด้วยรอยยิ้มมั่นใจ "
            f"ใครจะไปคิดว่าหลังจากพาเจ้าก้อนแป้งสองแฝดฝ่าฟันความหนาวเหน็บในยุค 70 มาได้ ประตูมิติกลับเชื่อมโยง"
            f"พาเธอกับลูกๆ วาร์ปข้ามเวลากลับมาสู่มหานครกรุงเทพฯ ปี 2026 พร้อมกับซูเปอร์มาร์เก็ตลับที่อัปเกรดเป็นห้างสรรพสินค้ายักษ์!\n\n"
            f"'แม่จ๋า! นมอัลมอนด์กับช็อกโกแลตสตรอว์เบอร์รีอร่อยที่สุดเลย!' เสี่ยวเป่าในชุดเดรสลูกไม้ตัวจิ๋ววิ่งเข้ามากอดขาเธอ "
            f"ส่วนต้าเป่าตัวน้อยสวมแว่นตากันแดดอันใหญ่กำลังนั่งกดแท็บเล็ตตรวจเช็กสต็อกสินค้าอย่างขะมักเขม้น\n\n"
            f"ทว่า... ขณะที่ความสุขกำลังอบอวล ประตูกระจกอัตโนมัติพลันเปิดออก ชายหนุ่มร่างสูงสง่าในชุดสูททหารสังเกตการณ์ "
            f"พร้อมแว่นกันแดดสีดำก้าวเข้ามา ใบหน้าคมคายดุจรูปสลักของเขาทำเอาพนักงานสาวๆ ในร้านลืมหายใจ!\n\n"
            f"'ผู้จัดการหลินม่าน...' เสียงทุ้มต่ำทรงพลังดังขึ้น 'ทิ้งลูกไว้แนวหลัง แล้วหนีมาเปิดห้างที่นี่ คิดว่าผมจะตามหาไม่เจอเหรอ?'\n\n"
            f"หลินม่านชะงักกึก... หัวใจกระตุกวูบ นั่นมันสามีทหารหนุ่มที่เธอคิดว่าหายสาบสูญไปแล้วนี่นา!\n\n"
            f"---\n"
            f"💬 **[คุยกับเงาพันจันทร์]**\n"
            f"ชอบตอนพิเศษแนว What-If นี้ไหมครับ? อยากให้มีภาคต่อของจักรวาลนี้ คอมเมนต์บอกกันได้เลยน้า! ❤️\n"
        )
    else:
        prose = (
            f"# {spin_off_title}\n\n"
            f"**ผู้แต่ง:** เงาพันจันทร์ | **คอนเซ็ปต์:** {trope['theme']}\n\n"
            f"---\n\n"
            f"เอกสารสัญญาหนาปึกถูกวางกระแทกลงบนโต๊ะทำงานไม้โอ๊กสุดหรู\n\n"
            f"'เซ็นชื่อซะ ท่านประธานกู้... หรือจะให้ฉันเรียกว่า อดีตประธาน ดีล่ะ?' รินดาในชุดสูทสีดำสนิทนั่งไขว่ห้างอยู่บนเก้าอี้ซีอีโอ "
            f"แววตาของเธอคมกริบและเย็นชาจนคนทั้งห้องประชุมแทบไม่กล้าหายใจ\n\n"
            f"ชายหนุ่มที่เคยยืนอยู่บนจุดสูงสุดของวงการธุรกิจกัดฟันแน่น เสื้อเชิ้ตของเขาปลดกระดุมเม็ดบนออก "
            f"แววตาที่เคยมองเธออย่างหยิ่งยโส บัดนี้เต็มไปด้วยความสับสน วิงวอน และคลั่งรักจนแทบคลั่ง\n\n"
            f"'ถ้าผมยอมเซ็น...' เสียงทุ้มของเขาสั่นเครือ 'คุณจะยอมให้ผมอยู่เคียงข้างคุณในฐานะผู้ช่วยส่วนตัวไหม รินดา?'\n\n"
            f"หญิงสาวหัวเราะเบาๆ ในลำคอ รอยยิ้มพราวเสน่ห์ผุดขึ้นที่มุมปาก: 'ขึ้นอยู่กับว่า... คุณจะปรนนิบัติเจ้านายคนใหม่ได้ดีแค่ไหนต่างหากล่ะ!'\n\n"
            f"---\n"
            f"💬 **[คุยกับเงาพันจันทร์]**\n"
            f"บทบาทสลับขั้ว สะใจสายแก้แค้นไหมครับ? คอมเมนต์แชร์ความรู้สึกกันได้เลยครับ! ❤️\n"
        )

    out_file = os.path.join(SPIN_OFF_DIR, f"{clean_title.replace(' ', '_')}_{trope_key}_SPIN_OFF.md")
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(prose)

    print(f"  ✨ สร้างตอนพิเศษ Spin-Off สำเร็จ: {out_file}")
    return {
        "title": spin_off_title,
        "file": out_file,
        "words": len(prose.split())
    }


if __name__ == "__main__":
    t = sys.argv[1] if len(sys.argv) > 1 else "คุณแม่ลูกแฝดยุค_70"
    generate_spin_off_chapter(t, "modern_au")
    generate_spin_off_chapter("เมื่อนางร้ายหมดรัก_ท่านประธานก็เริ่มคลั่ง", "role_reversal")
