def normalize_key(name: str) -> str:
    """ตัดสัญลักษณ์ underscore และช่องว่าง เหลือเฉพาะตัวอักษรและตัวเลขสำหรับการเปรียบเทียบเทียบเคียง"""
    if not name:
        return ""
    # ตัด extension เผื่อมี
    base = re.sub(r"\.(mp3|mp4|md|json|epub|jpg|png|txt)$", "", name, flags=re.IGNORECASE)
    # ตัดคำประเภท suffix ทั่วไป
    base = re.sub(r"_(Teaser|Chapter|Audiobook|AudioScript|Mega|Full|Compilation).*", "", base)
    return "".join(ch for ch in base if ch.isalnum()).lower()


def get_canonical_title(raw_name: str) -> str:
    """แปลงชื่อดิบเป็นชื่อทางการที่สวยงาม พร้อมแสดงผล"""
    if not raw_name:
        return ""
    
    clean_raw = raw_name.strip()
    if clean_raw in CANONICAL_TITLES:
        return CANONICAL_TITLES[clean_raw]
        
    # ลบ underscore
    clean_spaced = clean_raw.replace("_", " ")
    for k, v in CANONICAL_TITLES.items():
        if k in clean_raw or k.replace("_", " ") in clean_spaced:
            return v
            
    # ค้นหาด้วย normalized key
    n_key = normalize_key(clean_raw)
    for k, v in CANONICAL_TITLES.items():
        if n_key == normalize_key(k):
            return v

    # Fallback เป็นชื่อปกติแบบลบ underscore ซ้ำซ้อน
    return re.sub(r"\s+", " ", clean_spaced).strip()


def is_same_story(title_a: str, title_b: str) -> bool:
    """ตรวจสอบว่าชื่อ 2 ชื่อนี้เป็นเรื่องเดียวกันหรือไม่"""
    if not title_a or not title_b:
        return False
    if title_a == title_b:
        return True
    
    ca = get_canonical_title(title_a)
    cb = get_canonical_title(title_b)
    if ca and cb and ca == cb:
        return True
        
    ka = normalize_key(title_a)
    kb = normalize_key(title_b)
    if not ka or not kb:
        return False
    return ka == kb or (len(ka) > 5 and ka in kb) or (len(kb) > 5 and kb in ka)
