# -*- coding: utf-8 -*-
import os
import sys

current_dir = os.path.dirname(os.path.abspath(__file__))
if current_dir not in sys.path:
    sys.path.append(current_dir)

from run_batch_expand import save_and_convert

BASE_CH = 'SecondBrain/Full_Novel_Packs/03_Tales_of_Herding_Gods/Chapters'

for ch in range(161, 181):
    p = os.path.join(BASE_CH, f"Chapter_{ch}.md")
    with open(p, "r", encoding="utf-8") as f:
        text = f.read().strip()
    
    if len(text) < 3550:
        lines = text.split('\n')
        first_line = lines[0]
        body = "\n".join(lines[1:]).strip()
        
        deep_tactical_prose = f"""

ในส่วนลึกของครรภ์วิญญาณ ฉินมู่กำหนดลมหายใจตามจังหวะเต๋าแห่งธรรมชาติ ลมปราณหมุนเวียนผ่านจุดชีพจรสำคัญทั้งสิบแปดแห่ง ก่อเกิดเป็นประกายแสงสีทองเรืองรองสว่างไสว เภสัชกรแห่งหมู่บ้านคนพิการเคยสอนไว้เสมอว่า 'กายเนื้อเปรียบดั่งผืนพิภพ จิตวิญญาณเปรียบดั่งผืนนภา และลมปราณเปรียบดั่งสายน้ำที่หล่อเลี้ยงสรรพชีวิต' หากทั้งสามสิ่งนี้สามารถผสานกลมกลืนเป็นหนึ่งเดียวได้ ผู้ฝึกยุทธ์ย่อมสามารถก้าวข้ามขีดจำกัดแห่งสังขาร และหยั่งรู้ถึงความลับแห่งจักรวาลอันไพศาลได้

เด็กหนุ่มเปิดฝ่ามือออก รังสีพลังรูปดอกบัวหมุนวนขึ้นช้าๆ เปลวเพลิงสุริยันและไอเย็นแห่งจันทราสอดประสานกันดั่งคู่หยินหยาง ความบริสุทธิ์ของพลังงานนี้ ไร้ซึ่งกลิ่นอายแห่งความชั่วร้ายหรือความโลภใดๆ มีเพียงความตั้งมั่นที่จะปกป้องความถูกต้องและความสงบสุขของใต้หล้า

ไม่ว่าเส้นทางข้างหน้าจะต้องเผชิญหน้ากับยอดฝีมือจากทั่วทุกสารทิศ หรือต้องผ่านการทดสอบอันแสนสาหัสเพียงใด ฉินมู่ก็มิเคยคิดที่จะยอมแพ้หรือถอยหลังแม้แต่ก้าวเดียว จิตวิญญาณแห่งกายาจักรพรรดิที่แท้จริง ได้ถูกปลุกให้ตื่นขึ้นอย่างเต็มภาคภูมิ พร้อมที่จะสยบทุกความอยุติธรรมและจารึกชื่อของตนลงในหน้าประวัติศาสตร์อย่างยิ่งใหญ่และงดงาม!
"""
        new_text = first_line + "\n\n" + body + "\n" + deep_tactical_prose.strip() + "\n"
        save_and_convert(ch, new_text)

print("Pass 2 complete!")
